#Requires -Version 5
<#
.SYNOPSIS
  Upload key of {{APP_NAME}} ({{PACKAGE}}): creates it, or registers an existing one on this PC.
  Generated by the app-init skill. See SIGNING.md.

  -Create    First time: creates {{KEYSTORE_PATH}} (PKCS12, RSA 4096, alias {{ALIAS}}),
             stores the password in the Windows Credential Manager and writes the public
             fingerprints next to the key (keystore-info.json, upload_certificate.pem).
  -Register  New PC, or the key was restored from Bitwarden: checks the password against the
             keystore and stores it in the Credential Manager.

  Passwords are typed here, hidden. They are never written to disk in plaintext: Windows
  encrypts the credential (DPAPI, tied to your user) and gradle/signing.gradle reads it at build time.
#>
param(
    [switch]$Create,
    [switch]$Register,
    [string]$Keystore = "{{KEYSTORE_PATH}}",
    [string]$Alias = "{{ALIAS}}",
    [string]$Target = "{{CREDENTIAL}}"
)

$ErrorActionPreference = "Stop"

function Find-Keytool {
    $candidates = @(
        "$env:ProgramFiles\Android\Android Studio\jbr\bin\keytool.exe",
        "$env:LOCALAPPDATA\Programs\Android Studio\jbr\bin\keytool.exe"
    )
    if ($env:JAVA_HOME) { $candidates += "$env:JAVA_HOME\bin\keytool.exe" }
    foreach ($c in $candidates) { if (Test-Path $c) { return $c } }
    $cmd = Get-Command keytool -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    throw "keytool not found: install Android Studio or set JAVA_HOME."
}

function Read-Secret([string]$prompt) {
    $s = Read-Host $prompt -AsSecureString
    [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($s))
}

function Use-CredentialModule {
    if (-not (Get-Module -ListAvailable -Name CredentialManager)) {
        Write-Host "Installing the CredentialManager PowerShell module (CurrentUser)..."
        Install-Module CredentialManager -Scope CurrentUser -Force
    }
    Import-Module CredentialManager
}

function Test-Password([string]$keytool, [string]$pwd) {
    # keytool reports a wrong password on stderr: with "Stop" that would throw instead of returning.
    $ErrorActionPreference = "Continue"
    $env:APPINIT_KS_PASS = $pwd
    try {
        $out = & $keytool -list -v -keystore $Keystore -alias $Alias -storepass:env APPINIT_KS_PASS 2>&1 | Out-String
        return @{ ok = ($LASTEXITCODE -eq 0); text = $out }
    } finally {
        Remove-Item Env:APPINIT_KS_PASS -ErrorAction SilentlyContinue
    }
}

function Write-Info([string]$listing, [string]$keytool) {
    $dir = Split-Path $Keystore -Parent
    $sha256 = ([regex]::Match($listing, "SHA256:\s*([0-9A-F:]+)")).Groups[1].Value
    $sha1 = ([regex]::Match($listing, "SHA1:\s*([0-9A-F:]+)")).Groups[1].Value
    $until = ([regex]::Match($listing, "until:\s*(.+)")).Groups[1].Value.Trim()
    $info = [ordered]@{
        package = "{{PACKAGE}}"; keystore = (Split-Path $Keystore -Leaf); alias = $Alias; type = "PKCS12";
        role = "upload key (Play App Signing keeps the app signing key)";
        sha256 = $sha256; sha1 = $sha1; valid_until = $until; credential = $Target;
        written = (Get-Date -Format "yyyy-MM-dd")
    }
    $info | ConvertTo-Json | Set-Content -Encoding UTF8 (Join-Path $dir "keystore-info.json")
    $env:APPINIT_KS_PASS = $script:pwd
    try {
        & $keytool -exportcert -rfc -keystore $Keystore -alias $Alias -storepass:env APPINIT_KS_PASS `
            -file (Join-Path $dir "upload_certificate.pem") | Out-Null
    } finally { Remove-Item Env:APPINIT_KS_PASS -ErrorAction SilentlyContinue }
    Write-Host ""
    Write-Host "SHA-256: $sha256"
    Write-Host "SHA-1:   $sha1"
    Write-Host "Valid until: $until"
    Write-Host "Written (public data only): keystore-info.json, upload_certificate.pem in $dir"
}

if (-not ($Create -xor $Register)) { throw "Use -Create (new key) or -Register (existing key)." }
$keytool = Find-Keytool
Use-CredentialModule

if ($Create) {
    if (Test-Path $Keystore) {
        throw "$Keystore already exists. It is never overwritten: use -Register, or move it aside on purpose."
    }
    New-Item -ItemType Directory -Force (Split-Path $Keystore -Parent) | Out-Null
    Write-Host "=== New upload key for {{APP_NAME}} ==="
    Write-Host "Use the password you just generated in Bitwarden (references/firma.md, step 1)."
    $script:pwd = Read-Secret "Keystore password (min. 16 characters)"
    if ($script:pwd.Length -lt 16) { throw "Too short: generate a longer one in Bitwarden." }
    $again = Read-Secret "Repeat the password"
    if ($again -ne $script:pwd) { throw "The passwords do not match." }
    $org = Read-Host "Organization for the certificate [{{DEVELOPER}}]"
    if (-not $org) { $org = "{{DEVELOPER}}" }
    $country = Read-Host "Country code (2 letters) [BO]"
    if (-not $country) { $country = "BO" }
    $env:APPINIT_KS_PASS = $script:pwd
    try {
        # PKCS12 keeps one password for the store and the key.
        & $keytool -genkeypair -keystore $Keystore -storetype PKCS12 -alias $Alias -keyalg RSA -keysize 4096 `
            -validity 10000 -dname "CN=$org, O=$org, C=$country" `
            -storepass:env APPINIT_KS_PASS -keypass:env APPINIT_KS_PASS
        if ($LASTEXITCODE -ne 0) { throw "keytool failed." }
    } finally { Remove-Item Env:APPINIT_KS_PASS -ErrorAction SilentlyContinue }
} else {
    if (-not (Test-Path $Keystore)) { throw "No keystore at ${Keystore}: restore it from Bitwarden first (SIGNING.md)." }
    Write-Host "=== Register the upload key of {{APP_NAME}} on this PC ==="
    $a = Read-Host "Key alias [$Alias]"
    if ($a) { $Alias = $a }
    $script:pwd = Read-Secret "Keystore password"
}

$check = Test-Password $keytool $script:pwd
if (-not $check.ok) { throw "Wrong password or alias for $Keystore." }
New-StoredCredential -Target $Target -UserName $Alias -Password $script:pwd -Persist LocalMachine | Out-Null
Write-Host "Stored alias + password under '$Target' (Control Panel > Credential Manager > Windows Credentials)."
Write-Info $check.text $keytool
$script:pwd = $null

Write-Host ""
if ($Create) {
    Write-Host "NOW, before closing this window: back up the key (SIGNING.md > Backup):"
    Write-Host "  1. Bitwarden item: attach $(Split-Path $Keystore -Leaf), add SHA-256 / SHA-1 / alias."
    Write-Host "  2. Offline encrypted copy (USB)."
    Write-Host "Losing it means asking Google for an upload key reset; leaking it lets others publish updates."
}
Write-Host "Done. Android Studio's Run button and release builds now sign with this key."
